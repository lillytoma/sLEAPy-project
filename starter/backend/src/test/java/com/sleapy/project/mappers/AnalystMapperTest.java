    @Test
    void orderSavedThroughTradingMapperIsVisibleOnlyAfterCommit() {
        var client = new ClientEntity();
        client.setId(1L);
        var instrument = new InstrumentEntity();
        instrument.setId(1L);
        var status = new OrderStatus();
        status.setId(2L);
        var order = new OrderEntity();
        order.setClient(client);
        order.setInstrument(instrument);
        order.setStatus(status);
        order.setTradeType("BUY");
        order.setQuantity(new BigDecimal("2"));
        order.setPurchasePrice(new BigDecimal("10"));
        order.setTimeOfPurchase(START.plusDays(10).toLocalDate());
        order.setTimeFilled(order.getTimeOfPurchase());

        try (var writer = sessionFactory.openSession()) {
            writer.getMapper(OrderMapper.class).save(order);
            try (var reader = sessionFactory.openSession()) {
                assertEquals(3, reader.getMapper(AnalystMapper.class).countTrades(null, START, END));
            }
            writer.commit();
        }
        try (var reader = sessionFactory.openSession()) {
            var mapper = reader.getMapper(AnalystMapper.class);
            assertEquals(4, mapper.countTrades(null, START, END));
            assertEquals(0, new BigDecimal("370.75").compareTo(mapper.findTradeVolume(null, START, END)));
            assertEquals(3, mapper.findMostActiveInstruments(1L, START, END)
                    .stream().mapToLong(item -> item.getTotalTrades()).sum());
        }

        try (var writer = sessionFactory.openSession()) {
            order.setId(null);
            writer.getMapper(OrderMapper.class).save(order);
            writer.rollback();
        }
        try (var reader = sessionFactory.openSession()) {
            assertEquals(4, reader.getMapper(AnalystMapper.class).countTrades(null, START, END));
        }
    }

    @Test
    void periodAndClientFiltersExcludeUnfilledPrivilegedAndOutOfRangeOrders() {
        jdbc.update("INSERT INTO public.orders "
                + "(client_id, instrument_id, quantity, purchase_price, time_purchased, status) VALUES "
                + "(1, 1, 1, 999, '2026-10-02 12:00:00', 1), "
                + "(1, 1, 1, 999, '2026-10-02 12:00:00', 3), "
                + "(3, 1, 1, 999, '2026-10-02 12:00:00', 2), "
                + "(5, 1, 1, 999, '2026-10-02 12:00:00', 2), "
                + "(1, 1, 1, 999, '2026-09-30 23:59:59', 2), "
                + "(1, 1, 1, 999, '2026-11-01 00:00:00', 2)");
        try (var session = sessionFactory.openSession()) {
            var mapper = session.getMapper(AnalystMapper.class);
            assertEquals(3, mapper.countTrades(null, START, END));
            assertEquals(2, mapper.countTrades(1L, START, END));
            assertEquals(0, mapper.countTrades(3L, START, END));
            assertEquals(0, mapper.countTrades(5L, START, END));
            assertEquals(0, new BigDecimal("150.50").compareTo(mapper.findTradeVolume(1L, START, END)));
            assertEquals(2, mapper.findMostActiveInstruments(1L, START, END).size());
            var dayStart = START.plusDays(1);
            var dayEnd = START.plusDays(2).minusNanos(1);
            assertEquals(1, mapper.countTrades(null, dayStart, dayEnd));
            assertEquals(0, new BigDecimal("200.25").compareTo(mapper.findTradeVolume(null, dayStart, dayEnd)));
            assertEquals(1, mapper.findMostActiveInstruments(null, dayStart, dayEnd).getFirst().getTotalTrades());
            assertNull(mapper.findLatestTradeTime(1L, dayStart, dayEnd));
            assertEquals(1, mapper.findActivity(null, dayStart, dayEnd).size());
            assertTrue(mapper.findActivity(1L, dayStart, dayEnd).isEmpty());
            assertTrue(mapper.findActivity(3L, START, END).isEmpty());
            assertTrue(mapper.findActivity(5L, START, END).isEmpty());
        }
    }

    @Test
    void rangeIncludesBothBoundariesButNotFutureOrEarlierOrders() {
        var start = END.plusDays(1);
        var end = start.plusHours(12);
        for (var time : java.util.List.of(start.minusSeconds(1), start, end, end.plusSeconds(1))) {
            jdbc.update("INSERT INTO public.orders "
                    + "(client_id, instrument_id, quantity, purchase_price, time_purchased, status) "
                    + "VALUES (1, 1, 1, 1, ?, 2)", time);
        }
        try (var session = sessionFactory.openSession()) {
            var mapper = session.getMapper(AnalystMapper.class);
            assertEquals(2, mapper.countTrades(null, start, end));
            assertEquals(0, new BigDecimal("2").compareTo(mapper.findTradeVolume(null, start, end)));
        }
    }
