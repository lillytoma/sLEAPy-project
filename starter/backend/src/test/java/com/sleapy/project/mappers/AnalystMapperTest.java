    @Test
    void multipleCustomersApplyToEverySummaryQueryWithoutDuplicatesOrPrivilegedAccounts() {
        try (var session = sessionFactory.openSession()) {
            var mapper = session.getMapper(AnalystMapper.class);
            var ids = java.util.List.of(1L, 2L, 1L, 3L, 5L);
            assertEquals(3, mapper.countTradesForClients(ids, START, END));
            assertEquals(0, new BigDecimal("350.75").compareTo(mapper.findTradeVolumeForClients(ids, START, END)));
            assertEquals(2, mapper.findMostActiveInstrumentsForClients(ids, START, END).size());
            assertEquals(3, mapper.findActivityForClients(ids, START, END).size());
            assertEquals(mapper.findLatestTradeTime(null, START, END),
                    mapper.findLatestTradeTimeForClients(ids, START, END));
            assertEquals(3, mapper.findOrderDirectionsForClients(ids, START, END).stream()
                    .mapToLong(item -> item.getTotalTrades()).sum());
            assertEquals(1, mapper.countTradesForClients(java.util.List.of(2L), START, END));
            assertEquals(0, mapper.countTradesForClients(java.util.List.of(3L, 5L), START, END));
            assertEquals(3, mapper.countTradesForClients(java.util.List.of(), START, END));
        }
    }

    @Test
    void orderDirectionsUseFilledCustomerOrdersAndPreserveUnknownDirections() {
        jdbc.update("UPDATE public.orders SET trade_type = 'buy' WHERE client_id = 1 AND instrument_id = 1");
        jdbc.update("UPDATE public.orders SET trade_type = 'SELL' WHERE client_id = 2");
        jdbc.update("INSERT INTO public.orders "
                + "(client_id, instrument_id, quantity, purchase_price, time_purchased, status, trade_type) VALUES "
                + "(1, 1, 1, 1000, '2026-10-03 12:00:00', 1, 'BUY'), "
                + "(1, 1, 1, 1000, '2026-10-03 12:00:00', 3, 'SELL'), "
                + "(3, 1, 1, 1000, '2026-10-03 12:00:00', 2, 'BUY'), "
                + "(5, 1, 1, 1000, '2026-10-03 12:00:00', 2, 'SELL'), "
                + "(1, 1, 1, 1000, '2026-09-30 12:00:00', 2, 'BUY'), "
                + "(1, 1, 1, 1000, '2026-11-01 12:00:00', 2, 'SELL')");
        try (var session = sessionFactory.openSession()) {
            var mapper = session.getMapper(AnalystMapper.class);
            var directions = mapper.findOrderDirections(null, START, END);
            assertEquals(3, directions.size());
            assertEquals(3, directions.stream().mapToLong(item -> item.getTotalTrades()).sum());
            var buy = directions.stream().filter(item -> item.getDirection().equals("BUY")).findFirst().orElseThrow();
            assertEquals("Stock", buy.getInstrumentType());
            assertEquals(1, buy.getTotalTrades());
            assertEquals(0, new BigDecimal("100.50").compareTo(buy.getTradeVolume()));
            var sell = directions.stream().filter(item -> item.getDirection().equals("SELL")).findFirst().orElseThrow();
            assertEquals(0, new BigDecimal("200.25").compareTo(sell.getTradeVolume()));
            var unknown = directions.stream().filter(item -> item.getDirection().equals("UNKNOWN")).findFirst().orElseThrow();
            assertEquals("Other", unknown.getInstrumentType());
            assertEquals(0, new BigDecimal("50").compareTo(unknown.getTradeVolume()));
            assertEquals(2, mapper.findOrderDirections(1L, START, END).size());
            assertTrue(mapper.findOrderDirections(3L, START, END).isEmpty());
            assertTrue(mapper.findOrderDirections(5L, START, END).isEmpty());
            assertEquals(1, mapper.findOrderDirections(null, START, START.plusDays(1)).size());
        }
    }

